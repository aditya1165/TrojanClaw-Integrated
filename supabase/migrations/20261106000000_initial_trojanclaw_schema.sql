create schema if not exists extensions;
create extension if not exists vector with schema extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.documents (
    id uuid primary key default gen_random_uuid(),
    source_url text not null,
    page_title text,
    data_type text,
    campus text,
    chunk_text text not null,
    embedding extensions.vector(1536),
    chunk_index integer not null default 0,
    created_at timestamptz not null default now(),
    last_scraped timestamptz not null default now(),
    constraint documents_source_chunk_unique unique (source_url, chunk_index)
);

create index if not exists idx_documents_source_url
    on public.documents (source_url);
create index if not exists idx_documents_data_type
    on public.documents (data_type);
create index if not exists idx_documents_campus
    on public.documents (campus);
create index if not exists documents_embedding_hnsw_idx
    on public.documents using hnsw (embedding extensions.vector_cosine_ops);

create table if not exists public.piazza_data (
    id bigint generated by default as identity primary key,
    course_id text not null,
    post_id text,
    title text,
    source_url text,
    content_text text not null,
    raw_payload jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idx_piazza_data_course_id
    on public.piazza_data (course_id);
create index if not exists idx_piazza_data_post_id
    on public.piazza_data (post_id);
create unique index if not exists piazza_data_course_post_unique
    on public.piazza_data (course_id, post_id)
    where post_id is not null;

alter table public.documents enable row level security;
alter table public.piazza_data enable row level security;

-- These are private, server-managed tables. Direct Postgres connections and the
-- service role can access them; anon/authenticated API roles receive no policy.
revoke all on table public.documents from anon, authenticated;
revoke all on table public.piazza_data from anon, authenticated;
revoke all on sequence public.piazza_data_id_seq from anon, authenticated;
